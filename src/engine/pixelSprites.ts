const canvasCache = new Map<string, HTMLCanvasElement>();
const dataUrlCache = new Map<string, string>();

export function getSpriteCanvas(
  key: string,
  scale = 2,
  flipX = false,
  silhouette = false,
): HTMLCanvasElement {
  const cacheKey = `${key}_${scale}_${flipX ? 1 : 0}_${silhouette ? 1 : 0}`;
  const cached = canvasCache.get(cacheKey);
  if (cached) return cached;

  const def = SPRITE_DEFS[key] ?? SPRITE_DEFS.leaf_slime!;
  const size = 16 * scale;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;

  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < def.grid.length; y += 1) {
    const row = def.grid[y]!;
    for (let x = 0; x < row.length; x += 1) {
      const ch = row[x]!;
      if (ch === '.' || ch === ' ') continue;
      const color = silhouette ? '#222030' : def.palette[ch] ?? def.palette[ch.toLowerCase()];
      if (!color) continue;
      ctx.fillStyle = color;
      const drawX = flipX ? (15 - x) * scale : x * scale;
      ctx.fillRect(drawX, y * scale, scale, scale);
    }
  }

  canvasCache.set(cacheKey, canvas);
  return canvas;
}

export function getSpriteDataUrl(
  key: string,
  scale = 3,
  silhouette = false,
): string {
  const cacheKey = `${key}_${scale}_${silhouette ? 1 : 0}`;
  const cached = dataUrlCache.get(cacheKey);
  if (cached) return cached;
  if (typeof document === 'undefined') return '';
  const canvas = getSpriteCanvas(key, scale, false, silhouette);
  const url = canvas.toDataURL();
  dataUrlCache.set(cacheKey, url);
  return url;
}
